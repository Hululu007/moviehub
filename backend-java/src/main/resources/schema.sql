-- 观影中心 (MovieHub) MySQL 表结构 (自动初始化)

CREATE TABLE IF NOT EXISTS vod_source (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    source_key VARCHAR(64) NOT NULL UNIQUE COMMENT '片源唯一标识，如 ffzy',
    name VARCHAR(128) NOT NULL COMMENT '片源显示名称，如 非凡',
    api_url VARCHAR(512) NOT NULL COMMENT '苹果CMS标准接口地址',
    enabled TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用: 1启用, 0停用',
    sort_order INT NOT NULL DEFAULT 100 COMMENT '排序权重(越小越靠前)',
    latency_ms INT NOT NULL DEFAULT 0 COMMENT '服务端最近一次测速耗时(毫秒)',
    health_status VARCHAR(32) NOT NULL DEFAULT 'ONLINE' COMMENT '状态: ONLINE / SLOW / OFFLINE',
    last_checked_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '最近测速时间',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS live_channel (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    channel_code VARCHAR(64) NOT NULL UNIQUE COMMENT '频道唯一编码',
    name VARCHAR(128) NOT NULL COMMENT '频道名称，如 CCTV-1 综合',
    group_name VARCHAR(64) NOT NULL DEFAULT '央视频道' COMMENT '频道分组',
    stream_url VARCHAR(1024) NOT NULL COMMENT 'M3U8直播流地址',
    enabled TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用: 1启用, 0停用',
    sort_order INT NOT NULL DEFAULT 100 COMMENT '排序权重',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS music_script (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    script_key VARCHAR(64) NOT NULL UNIQUE COMMENT '音源标识',
    name VARCHAR(128) NOT NULL COMMENT '音源名称',
    script_url VARCHAR(1024) NOT NULL COMMENT '音源地址',
    enabled TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用: 1启用, 0停用',
    sort_order INT NOT NULL DEFAULT 100 COMMENT '排序权重',
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS app_meta (
    meta_key VARCHAR(64) PRIMARY KEY,
    meta_value VARCHAR(512) NOT NULL,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
